QList<maxchat::irc::ServerEndpoint> allServers(const NetworkDefaults& network) {
    QList<maxchat::irc::ServerEndpoint> servers;
    servers.reserve(network.failovers.size() + 1);
    servers.append(network.primary);
    servers.append(network.failovers);
    return servers;
}

maxchat::irc::ServerEndpoint parseServerSpec(const QString& spec, int defaultPort,
                                             bool defaultTls) {
    QString host = spec.trimmed();
    int port = defaultPort;
    bool tls = defaultTls;

    const int colon = host.lastIndexOf(QLatin1Char(':'));
    if (colon > 0 && colon + 1 < host.size()) {
        QString portText = host.mid(colon + 1).trimmed();
        host = host.left(colon).trimmed();
        if (portText.startsWith(QLatin1Char('+'))) {
            tls = true;
            portText.remove(0, 1);
        } else {
            tls = false;
        }
        bool ok = false;
        const int parsedPort = portText.toInt(&ok);
        if (ok) {
            port = parsedPort;
        }
    }

    return makeEndpoint(host, port, tls);
}

QString serverSpec(const maxchat::irc::ServerEndpoint& server) {
    return QStringLiteral("%1:%2%3").arg(server.host, server.tls ? QStringLiteral("+") : QString(),
                                         QString::number(server.port));
}

