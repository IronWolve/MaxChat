maxchat::irc::ServerEndpoint makeEndpoint(QString host, int port, bool tls) {
    maxchat::irc::ServerEndpoint endpoint;
    endpoint.host = std::move(host);
    endpoint.port = port;
    endpoint.tls = tls;
    return endpoint;
}

